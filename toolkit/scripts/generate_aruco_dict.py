def main() -> None:
    repo_root = Path(__file__).resolve().parents[2]
    patterns = extract_dict_5x5_patterns(max_id=5)
    py_out = repo_root / "toolkit" / "src" / "yardstick" / "aruco_dict_data.py"
    swift_out = repo_root / "ios" / "Yardstick" / "Sources" / "ArUcoDictionaryData.swift"
