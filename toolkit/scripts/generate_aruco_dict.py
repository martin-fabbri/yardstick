"""Generate ArUco DICT_5X5_250 bit patterns (IDs 0-5 and rotations) from OpenCV's published dictionary.

Requirement YS-30 / Q007:
The dictionary's bit patterns are data generated by a toolkit script from OpenCV's
published dictionary (Apache License 2.0), with an attribution line; no detector code is copied.
"""

from __future__ import annotations

import json
from pathlib import Path

import cv2
import numpy as np


def extract_dict_5x5_patterns(max_id: int = 5) -> dict[int, list[int]]:
    """Return 25-bit integers (row-major 5x5) for each rotation 0, 90, 180, 270 CW."""
    aruco_dict = cv2.aruco.getPredefinedDictionary(cv2.aruco.DICT_5X5_250)
    patterns: dict[int, list[int]] = {}
    for marker_id in range(max_id + 1):
        # Generate a 7x7 cell image (1 pixel per cell -> 7x7 pixels, inner 5x5 is payload)
        img = cv2.aruco.generateImageMarker(aruco_dict, marker_id, 7)
        bits_5x5 = (img[1:6, 1:6] > 127).astype(np.uint8)
        rotations: list[int] = []
        for rot in range(4):
            # rot=0 is canonical upright; rot=1 is rotated 90 deg clockwise in image, etc.
            rotated = np.rot90(bits_5x5, k=-rot)
            val = 0
            for bit in rotated.flatten():
                val = (val << 1) | int(bit)
            rotations.append(val)
        patterns[marker_id] = rotations
    return patterns


