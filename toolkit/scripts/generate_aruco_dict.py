        "// Generated by toolkit/scripts/generate_aruco_dict.py",
        "// Attribution: Bit patterns for DICT_5X5_250 (IDs 0-5) extracted from",
        "// OpenCV's published cv2.aruco.DICT_5X5_250 dictionary (https://opencv.org,",
        "// Apache License 2.0). No OpenCV detector code is copied.",
        "",
        "import Foundation",
